    private void tblPaquetesMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblPaquetesMouseClicked
        int fila = tblPaquetes.getSelectedRow();
        if (fila >= 0) {
            txtCodigo.setText(modeloPaquetes.getValueAt(fila, 0).toString());
            txtNombre.setText(modeloPaquetes.getValueAt(fila, 1).toString());
            PaqueteTuristico p = agencia.getGestionPaquete().buscar(txtCodigo.getText());
            if (p != null) {
                txtDias.setText(String.valueOf(p.getDuracionDias()));
                txtNoches.setText(String.valueOf(p.getDuracionNoches()));
                cboTipo.setSelectedItem(p.getTipo());
                txtPrecio.setText(String.valueOf(p.getPrecioPorPersona()));
                txtFechaSalida.setText(p.getFechaSalida());
                txtFechaRetorno.setText(p.getFechaRetorno());
                txtCupo.setText(String.valueOf(p.getCupoMaximo()));
                cboEstado.setSelectedItem(p.getEstado());
            }
        }
    }//GEN-LAST:event_tblPaquetesMouseClicked

