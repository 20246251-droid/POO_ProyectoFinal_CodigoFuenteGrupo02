    private void cargarDestinos() {
        cboDestino.removeAllItems();
        DestinoTuristico[] destinos = agencia.getGestionDestino().obtenerDestinos();
        int total = agencia.getGestionDestino().obtenerTotalDestinos();
        for (int i = 0; i < total; i++) {
            cboDestino.addItem(destinos[i].getNombre());
        }
    }

    private PaqueteTuristico construirPaquete() {
        try {
            return new PaqueteTuristico(txtCodigo.getText().trim(), txtNombre.getText().trim(),
                    Integer.parseInt(txtDias.getText().trim()),
                    Integer.parseInt(txtNoches.getText().trim()),
                    cboTipo.getSelectedItem().toString(),
                    Double.parseDouble(txtPrecio.getText().trim()),
                    txtFechaSalida.getText().trim(), txtFechaRetorno.getText().trim(),
                    Integer.parseInt(txtCupo.getText().trim()),
                    cboEstado.getSelectedItem().toString());
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Verifique los valores numericos (dias, noches, precio, cupo)");
            return null;
        }
    }

    private void registrarPaquete() {
        if (txtCodigo.getText().trim().equals("") || txtNombre.getText().trim().equals("")) {
            JOptionPane.showMessageDialog(this, "Ingrese codigo y nombre del paquete");
            return;
        }
        PaqueteTuristico paquete = construirPaquete();
        if (paquete == null) {
            return;
        }
        if (agencia.getGestionPaquete().registrar(paquete)) {
            JOptionPane.showMessageDialog(this, "Paquete registrado. Ahora agregue destinos, servicios e itinerario.");
            listarPaquetes();
        } else {
            JOptionPane.showMessageDialog(this, "No se pudo registrar (codigo duplicado)");
        }
    }

    private void modificarPaquete() {
        PaqueteTuristico paquete = construirPaquete();
        if (paquete == null) {
            return;
        }
        if (agencia.getGestionPaquete().actualizar(paquete)) {
            JOptionPane.showMessageDialog(this, "Paquete modificado correctamente");
            listarPaquetes();
        } else {
            JOptionPane.showMessageDialog(this, "No se encontro el paquete");
        }
    }

    private void eliminarPaquete() {
        if (agencia.getGestionPaquete().eliminar(txtCodigo.getText().trim())) {
            JOptionPane.showMessageDialog(this, "Paquete eliminado");
            listarPaquetes();
        } else {
            JOptionPane.showMessageDialog(this, "No se encontro el paquete");
        }
    }

    private void agregarDestino() {
        PaqueteTuristico paquete = agencia.getGestionPaquete().buscar(txtCodigo.getText().trim());
        if (paquete == null) {
            JOptionPane.showMessageDialog(this, "Primero seleccione o registre el paquete");
            return;
        }
        if (cboDestino.getSelectedItem() == null) {
            JOptionPane.showMessageDialog(this, "No hay destinos registrados");
            return;
        }
        DestinoTuristico destino = agencia.getGestionDestino().buscar(cboDestino.getSelectedItem().toString());
        if (paquete.agregarDestino(destino)) {
            JOptionPane.showMessageDialog(this, "Destino agregado al paquete");
            listarPaquetes();
        } else {
            JOptionPane.showMessageDialog(this, "No se pudo agregar (el destino ya esta en el paquete o no hay espacio)");
        }
    }

    private void quitarDestino() {
        PaqueteTuristico paquete = agencia.getGestionPaquete().buscar(txtCodigo.getText().trim());
        if (paquete == null) {
            JOptionPane.showMessageDialog(this, "Primero seleccione el paquete en la tabla");
            return;
        }
        if (cboDestino.getSelectedItem() == null) {
            JOptionPane.showMessageDialog(this, "Seleccione en el combo el destino a quitar");
            return;
        }
        if (paquete.eliminarDestino(cboDestino.getSelectedItem().toString())) {
            JOptionPane.showMessageDialog(this, "Destino quitado del paquete");
            listarPaquetes();
        } else {
            JOptionPane.showMessageDialog(this, "Ese destino no esta incluido en el paquete");
        }
    }

    private void listarPaquetes() {
        modeloPaquetes.setRowCount(0);
        PaqueteTuristico[] paquetes = agencia.getGestionPaquete().obtenerPaquetes();
        int total = agencia.getGestionPaquete().obtenerTotalPaquetes();
        for (int i = 0; i < total; i++) {
            PaqueteTuristico p = paquetes[i];
            modeloPaquetes.addRow(new Object[]{p.getCodigo(), p.getNombre(), p.obtenerNombresDestinos(),
                p.getDuracionDias() + "D/" + p.getDuracionNoches() + "N", p.getTipo(),
                p.getPrecioPorPersona(), p.getFechaSalida(), p.getFechaRetorno(),
                p.getCupoDisponible() + "/" + p.getCupoMaximo(), p.getEstado()});
        }
    }

    private void listarServicios() {
        PaqueteTuristico paquete = agencia.getGestionPaquete().buscar(txtCodigoServicio.getText().trim());
        if (paquete == null) {
            JOptionPane.showMessageDialog(this, "No se encontro el paquete");
            return;
        }
        modeloServicios.setRowCount(0);
        ServicioIncluido[] servicios = paquete.obtenerServicios();
        for (int i = 0; i < paquete.obtenerTotalServicios(); i++) {
            modeloServicios.addRow(new Object[]{servicios[i].getTipo(), servicios[i].getDescripcion()});
        }
    }

    private void agregarServicio() {
        PaqueteTuristico paquete = agencia.getGestionPaquete().buscar(txtCodigoServicio.getText().trim());
        if (paquete == null) {
            JOptionPane.showMessageDialog(this, "No se encontro el paquete");
            return;
        }
        if (txtDescripcionServicio.getText().trim().equals("")) {
            JOptionPane.showMessageDialog(this, "Ingrese la descripcion del servicio");
            return;
        }
        paquete.agregarServicio(new ServicioIncluido(cboTipoServicio.getSelectedItem().toString(),
                txtDescripcionServicio.getText().trim()));
        txtDescripcionServicio.setText("");
        listarServicios();
    }

    private void quitarServicio() {
        PaqueteTuristico paquete = agencia.getGestionPaquete().buscar(txtCodigoServicio.getText().trim());
        int fila = tblServicios.getSelectedRow();
        if (paquete == null || fila < 0) {
            JOptionPane.showMessageDialog(this, "Seleccione un servicio de la tabla");
            return;
        }
        paquete.eliminarServicio(fila);
        listarServicios();
    }

    private void listarItinerario() {
        PaqueteTuristico paquete = agencia.getGestionPaquete().buscar(txtCodigoItinerario.getText().trim());
        if (paquete == null) {
            JOptionPane.showMessageDialog(this, "No se encontro el paquete");
            return;
        }
        modeloItinerario.setRowCount(0);
        ItinerarioDia[] itinerario = paquete.obtenerItinerario();
        for (int i = 0; i < paquete.obtenerTotalDiasItinerario(); i++) {
            modeloItinerario.addRow(new Object[]{itinerario[i].getDia(), itinerario[i].getDescripcion()});
        }
    }

    private void agregarDia() {
        PaqueteTuristico paquete = agencia.getGestionPaquete().buscar(txtCodigoItinerario.getText().trim());
        if (paquete == null) {
            JOptionPane.showMessageDialog(this, "No se encontro el paquete");
            return;
        }
        try {
            int dia = Integer.parseInt(txtDiaItinerario.getText().trim());
            if (txtDescripcionItinerario.getText().trim().equals("")) {
                JOptionPane.showMessageDialog(this, "Ingrese la descripcion de actividades");
                return;
            }
            paquete.agregarDiaItinerario(new ItinerarioDia(dia, txtDescripcionItinerario.getText().trim()));
            txtDiaItinerario.setText("");
            txtDescripcionItinerario.setText("");
            listarItinerario();
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "El dia debe ser un numero");
        }
    }

